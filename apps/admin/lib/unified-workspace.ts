export function workspaceApi(level: string, id: string) {
  return `v1/admin/content/workspace/${encodeURIComponent(level)}/${encodeURIComponent(id)}`;
}
export function workspaceHref(target: WorkspaceTarget, extra: Record<string, string | null | undefined> = {}) {
  const query = new URLSearchParams({ tab: target.tab });
  const values: Record<string, string | null | undefined> = {
    phase: target.phase, section: target.section, field: target.field, revision: target.revision == null ? undefined : String(target.revision), binding: target.binding, scope_type: target.scope_type, scope_id: target.scope_id, term: target.term, kind: target.kind, floor_from: target.floor_from == null ? undefined : String(target.floor_from), floor_to: target.floor_to == null ? undefined : String(target.floor_to), question: target.question_key,
    faq: target.faq, cluster: target.cluster, unit_type: target.unit_type, facility: target.facility,
    item: target.item, building: target.building, grain: target.grain, category: target.media_category, usage: target.usage, target_type: target.target_type, target_key: target.target_key, floor: target.floor == null ? undefined : String(target.floor), tags: target.tags?.join(","), rule: target.rule_key, media_role: target.media_role, version: target.version, draft_at: target.draft_at, asset: target.asset_id, web_page: target.web_page,
  };
  if (target.media_slot) Object.assign(values, {
    rule: target.media_slot.rule_key, category: target.media_slot.media_category, target_type: target.media_slot.target_type,
    target_key: target.media_slot.target_key, floor: target.media_slot.floor == null ? undefined : String(target.media_slot.floor),
    tags: target.media_slot.tags.join(","), usage: target.media_slot.usage, media_role: target.media_slot.media_role,
    section: target.media_slot.media_role ? "canonical" : "upload",
    media_upload: target.media_slot.media_role ? "1" : undefined,
  });
  for (const [key, value] of Object.entries({ ...values, ...extra })) if (value != null && value !== "") query.set(key, value);
  return `/website/${encodeURIComponent(target.level)}/${encodeURIComponent(target.id)}?${query}`;
}
export function queryParameters(value: Record<string, string | string[] | undefined>) {
  const query = new URLSearchParams();
  for (const [key, item] of Object.entries(value)) {
    if (typeof item === "string") query.append(key, item);
    else if (Array.isArray(item)) for (const entry of item) query.append(key, entry);
  }
  return query;
}
// Temporary legacy redirects preserve every query before replacing only routing keys.
export function legacyWorkspaceHref(path: string, query: URLSearchParams): string | null {
  const copy = new URLSearchParams(query);
  const project = query.get("project"), brand = query.get("brand"), tab = query.get("tab");
  if (path === "/releases" || path === "/faq" && tab === "publication") return `/publish${copy.size ? "?" + copy : ""}`;
  let target: WorkspaceTarget | null = null;
  if (path === "/" && (project || brand)) {
    const field = query.get("field") ?? "", history = query.has("version") || query.has("draft_at");
    const models = /^(models?|commercial_type|price)\./.test(field), media = /^(assets?|hero|thumbnail)(\.|$)/.test(field) || query.has("media_role");
    const supplementary = /^(project\.)?(meta_title|meta_description|website_content|facilities)(\.|$)/.test(field);
    target = { level: brand ? "brand" : "project", id: (brand || project)!, tab: history ? "history" : models ? "unit-types" : media ? "media" : "data", section: media ? "canonical" : supplementary ? "supplementary" : "identity" };
    if (tab === "faq") target = { level: brand ? "brand" : "project", id: (brand || project)!, tab: "faq" };
  }
  if (path === "/content" && (project || brand)) target = { level: brand ? "brand" : "project", id: (brand || project)!, tab: tab === "readiness" ? "overview" : "data", section: tab || (brand ? "contacts" : "facts") };
  if (path === "/media" && tab !== "rules" && project) target = { level: "project", id: project, tab: "media", section: tab || "checklist" };
  if (path === "/faq" && tab === "contacts") target = { level: "corporate", id: "sena", tab: "data", section: "contacts" };
  if (path === "/faq" && query.get("faq") === "new") target = { level: "corporate", id: "sena", tab: "faq" };
  if (target) {
    copy.delete("project"); copy.delete("brand"); copy.delete("view"); copy.delete("tab");
    if (copy.has("question_key")) { if (!copy.has("question")) copy.set("question", copy.get("question_key")!); copy.delete("question_key"); }
    if (copy.has("media_category")) { copy.set("category", copy.get("media_category")!); copy.delete("media_category"); }
    if (copy.has("rule_key")) { copy.set("rule", copy.get("rule_key")!); copy.delete("rule_key"); }
    if (copy.has("tags")) {
      try { const tags: unknown = JSON.parse(copy.get("tags")!); if (Array.isArray(tags) && tags.every(tag => typeof tag === "string")) copy.set("tags", tags.join(",")); }
      catch { /* Existing comma-separated tag codes already use the editor format. */ }
    }
    const extras = Object.fromEntries(copy);
    return workspaceHref(target, extras);
  }
  if (path === "/content/fields") return "/settings?section=fields";
  if (path === "/media" && tab === "rules") { copy.set("section", "media-rules"); copy.delete("tab"); return `/settings?${copy}`; }
  if (path === "/faq" && (tab === "bank" || tab === "glossary")) { copy.set("section", tab); copy.delete("tab"); return `/settings?${copy}`; }
  if (path === "/faq" && tab === "coverage") { copy.delete("tab"); copy.set("section", "coverage"); return `/home?${copy}`; }
  if (["/", "/content", "/media", "/faq"].includes(path)) {
    if (path === "/faq") copy.set("intent", "faq");
    if (path === "/media") copy.set("intent", "media");
    if (query.get("faq")) { copy.set("legacy_faq", query.get("faq")!); copy.delete("faq"); }
    if (query.get("cluster")) { copy.set("legacy_cluster", query.get("cluster")!); copy.delete("cluster"); }
    return `/website${copy.size ? "?" + copy : ""}`;
  }
  return null;
}

