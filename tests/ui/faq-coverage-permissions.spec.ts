import { expect, test } from '@playwright/test';

test('FAQ coverage discards cached project evidence when Projects V is revoked', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  expect((await page.request.post('/api/local-session', { headers: { Origin: 'http://127.0.0.1:3000' }, data: { role: 'viewer' } })).ok()).toBeTruthy();
  const original = (await (await page.request.get('/api/hub/v1/me')).json()).data;
  let account = structuredClone(original), checks = 0, coverageReads = 0;
  await page.route('**/api/hub/v1/me', route => { checks++; return route.fulfill({ json: { data: account } }); });
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/hub/v1/admin/faq-coverage') coverageReads++; });
  await page.goto('/faq?tab=coverage');
  await expect(page.getByRole('region', { name: 'ตารางความครบตามโครงการ', exact: true })).toBeVisible();
  const before = checks;
  account.capabilities.tabs.projects.view = false;
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect.poll(() => checks).toBeGreaterThan(before);
  await expect(page.getByText('ต้องมีสิทธิ์ดูคลังความรู้และโครงการเพื่อดูข้อเท็จจริงประกอบคำตอบ', { exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'ตารางความครบตามโครงการ', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'งานข้อเท็จจริงที่ขาด', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/project-content-phase6/revoked-390.png', fullPage: true });
  const reads = coverageReads;
  account = structuredClone(original);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect.poll(() => coverageReads).toBeGreaterThan(reads);
  await expect(page.getByRole('region', { name: 'ตารางความครบตามโครงการ', exact: true })).toBeVisible();
});

test('FAQ applicability clears resolved membership on source revocation and retains the unsaved answer', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  expect((await page.request.post('/api/local-session', { headers: { Origin: 'http://127.0.0.1:3000' }, data: { role: 'editor' } })).ok()).toBeTruthy();
  const original = (await (await page.request.get('/api/hub/v1/me')).json()).data;
  let account = structuredClone(original), checks = 0;
  await page.route('**/api/hub/v1/me', route => { checks++; return route.fulfill({ json: { data: account } }); });
  await page.goto('/website/corporate/sena?tab=faq&faq=new');
  await page.locator('#faq-short_answer-th').fill('ข้อความร่างที่ยังไม่บันทึก');
  await page.getByText('เลือกโครงการด้วยเงื่อนไข', { exact: true }).click();
  await page.getByRole('listbox', { name: 'ประเภทที่อยู่อาศัยในเงื่อนไข', exact: true }).selectOption('condominium');
  const preview = page.getByRole('button', { name: 'ดูรายชื่อเฟสที่ตรงเงื่อนไข', exact: true });
  const resolved = page.getByText(/ตรงเงื่อนไข \d+ เฟส · ยังไม่ตรึงเพื่อเผยแพร่/);
  await preview.click();
  await expect(resolved).toBeVisible();
  const before = checks;
  account.capabilities.tabs.projects.view = false;
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect.poll(() => checks).toBeGreaterThan(before);
  await expect(resolved).toHaveCount(0);
  const conditions = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'เลือกโครงการด้วยเงื่อนไข' }) });
  await expect(conditions.locator('select').first()).toBeDisabled();
  const recovered = page.getByRole('complementary', { name: 'ข้อความที่คุณกรอก', exact: true });
  await expect(recovered.getByRole('textbox', { name: 'คำตอบสั้น', exact: true })).toHaveValue('ข้อความร่างที่ยังไม่บันทึก');
  account = structuredClone(original);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(conditions.locator('select').first()).toBeEnabled();
  await conditions.locator('summary').click();
  await page.getByRole('listbox', { name: 'ประเภทที่อยู่อาศัยในเงื่อนไข', exact: true }).selectOption('condominium');
  await expect(resolved).toHaveCount(0);
  await preview.click();
  await expect(resolved).toBeVisible();
});
